    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
     if (campoNombre.getText().isEmpty() || campoApellido.getText().isEmpty())
    {
      JOptionPane.showMessageDialog(null,"Campos vacios!");
    } 
     else
    {
        conexion  objetoConexion = new conexion();
        String Consulta= "INSERT INTO proveedores(nombre, apellido, telefono, direccion) VALUES (?,?,?,?);";
        try{
            CallableStatement cs = objetoConexion.establecerConexion().prepareCall(Consulta);
            cs.setString(1,campoNombre.getText());
            cs.setString(2,campoApellido.getText());
            cs.setString(3,campoTelefono.getText());
            cs.setString(4,campoDireccion.getText());
            cs.execute();
            
           
            JOptionPane.showMessageDialog(null,"Se inserto correctamente!");
        } catch(Exception e ){
            
            JOptionPane.showMessageDialog(null,"Error al isnertar registro!,error:"+e.toString());
        }
    }
        proveedores ObjetoProveedores = new proveedores();
        ObjetoProveedores.MostrarProveedores(tabla);
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        conexion objetoConexion = new conexion();
        String editar ="UPDATE proveedores SET proveedores.nombre=?,proveedores.apellido=?,proveedores.telefono=?,proveedores.direccion=? where proveedores.id=?";
        try{
        CallableStatement cs = objetoConexion.establecerConexion().prepareCall(editar);
            cs.setString(1,campoNombre.getText());
            cs.setString(2,campoApellido.getText());
            cs.setString(3,campoTelefono.getText());
            cs.setString(4,campoDireccion.getText());
            cs.setString(5,campoId.getText());
            cs.execute(); 
        JOptionPane.showMessageDialog(null,"Modificacion exitosa!");
        
        }catch (SQLException e){
            
             JOptionPane.showMessageDialog(null,"Error al intentar modificar, error:"+ e.toString()); 
        } 
        proveedores ObjetoProveedores = new proveedores();
        ObjetoProveedores.MostrarProveedores(tabla);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void tablaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaMouseClicked
        try{
            int fila = tabla.getSelectedRow();
            if (fila >=0){
                campoId.setText((tabla.getValueAt(fila,0).toString()));
                campoNombre.setText((tabla.getValueAt(fila,1).toString()));
                campoApellido.setText((tabla.getValueAt(fila,2).toString()));
                campoTelefono.setText((tabla.getValueAt(fila,3).toString()));
                campoDireccion.setText((tabla.getValueAt(fila,4).toString()));               
            }   
            else{
                JOptionPane.showMessageDialog(null,"Fila no selecionada");
            }
            
        }catch(Exception e ){
             JOptionPane.showMessageDialog(null,"Error de selecion, error:"+e.toString());
           
        }
    }//GEN-LAST:event_tablaMouseClicked

