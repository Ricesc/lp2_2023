    private void tablaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaMouseClicked
        try{
             
            int fila = tabla.getSelectedRow();
            if (fila >=0){
                campoId.setText((tabla.getValueAt(fila,0).toString()));
                campoUsuario.setText((tabla.getValueAt(fila,1).toString()));
                campoEmail.setText((tabla.getValueAt(fila,2).toString()));
                campoPassword.setText((tabla.getValueAt(fila,3).toString()));
                String estado= tabla.getValueAt(fila,4).toString();
                if(estado.equals("Activo")){
                   campoActivo.setSelected(true);
               } else {
                   campoInactivo.setSelected(true);
               }
                campoRol.setSelectedItem(tabla.getValueAt(fila,5).toString());
                Date fecha = new SimpleDateFormat("yyyy-MM-dd").parse((String)tabla.getValueAt(fila,6).toString());
                campoFechaDeRegistro.setDate(fecha);
            
   
            }   
            else{
                JOptionPane.showMessageDialog(null,"Fila no selecionada");
            }
            
        }catch(Exception e ){
             JOptionPane.showMessageDialog(null,"Error de selecion, error:"+e.toString());
           
        }
    }//GEN-LAST:event_tablaMouseClicked

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        int aux; 
        aux=0;
        if(campoActivo.isSelected() || campoInactivo.isSelected()){
              aux=1;
          }
        
        if (campoUsuario.getText().isEmpty() || campoEmail.getText().isEmpty() || campoPassword.getText().isEmpty()
         || aux==0 || campoRol.getSelectedItem()==null || campoFechaDeRegistro.getDate()==null)
    {
      JOptionPane.showMessageDialog(null,"Campos vacios!");
    } 
     else
    {
        conexion  objetoConexion = new conexion();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String date = sdf.format(campoFechaDeRegistro.getDate());
        String Consulta= "INSERT INTO usuario(usuario, email, password, estado,rol,fechaDeRegistro) VALUES (?,?,?,?,?,?);";
        try{
            CallableStatement cs = objetoConexion.establecerConexion().prepareCall(Consulta);
            cs.setString(1,campoUsuario.getText());
            cs.setString(2,campoEmail.getText());
            cs.setString(3,campoPassword.getText());
            if(campoActivo.isSelected()){
            cs.setString(4,campoActivo.getText());
            }else if(campoInactivo.isSelected()){
            cs.setString(4,campoInactivo.getText());
            }
            cs.setString(5, campoRol.getSelectedItem().toString());
            cs.setString(6,date);
            
            
            cs.execute();
            
            JOptionPane.showMessageDialog(null,"Se inserto correctamente!");
        } catch(Exception e ){
            
            JOptionPane.showMessageDialog(null,"Error al isnertar registro!,error:"+e.toString());
        }
    }
        usuario ObjetoUsuario = new usuario();
        ObjetoUsuario.MostrarUsuario(tabla);
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String dateeditar = sdf.format(campoFechaDeRegistro.getDate());
        conexion objetoConexion = new conexion();
        String editar ="UPDATE usuario SET usuario.usuario=?,usuario.email=?,usuario.password=?,usuario.estado=?,usuario.rol=?,usuario.fechaDeRegistro=? where usuario.id=?";
        try{
        CallableStatement cs = objetoConexion.establecerConexion().prepareCall(editar);
            cs.setString(1,campoUsuario.getText());
            cs.setString(2,campoEmail.getText());
            cs.setString(3,campoPassword.getText());
            if(campoActivo.isSelected()){
            cs.setString(4,campoActivo.getText());
            }else if(campoInactivo.isSelected()){
            cs.setString(4,campoInactivo.getText());
            }
            cs.setString(5, campoRol.getSelectedItem().toString());
            cs.setString(6,dateeditar);
            cs.setString(7,campoId.getText());
            cs.execute(); 
        JOptionPane.showMessageDialog(null,"Modificacion exitosa!");
        
        }catch (SQLException e){
            
             JOptionPane.showMessageDialog(null,"Error al intentar modificar, error:"+ e.toString()); 
        } 
        
        usuario ObjetoUsuario = new usuario();
        ObjetoUsuario.MostrarUsuario(tabla);
    }//GEN-LAST:event_btnEditarActionPerformed

