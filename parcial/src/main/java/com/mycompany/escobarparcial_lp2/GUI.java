    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        models.addRow(new Object[]
        {campoCodigo.getText(),campoDescripcion.getText(),campoPrecio.getText(),campoCantidad.getText(),campoProveedor.getText()});
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tabla.getSelectedRow();
        models.setValueAt(campoCodigo.getText(),fila,0);
        models.setValueAt(campoDescripcion.getText(),fila,1);
        models.setValueAt(campoPrecio.getText(),fila,2);
        models.setValueAt(campoCantidad.getText(),fila,3);
        models.setValueAt(campoProveedor.getText(),fila,4);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tabla.getSelectedRow();
        models.removeRow(fila);
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        int fila = tabla.getRowCount();
        for(int i=0;i<fila;i++){
            models.removeRow(0);
        }
    }//GEN-LAST:event_btnLimpiarActionPerformed

