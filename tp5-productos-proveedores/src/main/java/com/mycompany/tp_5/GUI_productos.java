    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        
     if (campoCodigo.getText().isEmpty() || campoNombre.getText().isEmpty() || campoDescripcion.getText().isEmpty()
         )
    {
      JOptionPane.showMessageDialog(null,"Campos vacios!");
    } 
     else
    {
        conexion  objetoConexion = new conexion();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String date = sdf.format(campoVencimiento.getDate());
        String Consulta= "INSERT INTO productos(codigo, nombre, descripcion, categoria,vencimiento,cantidad,cantidad_minima,estado) VALUES (?,?,?,?,?,?,?,?);";
        try{
            CallableStatement cs = objetoConexion.establecerConexion().prepareCall(Consulta);
            cs.setString(1,campoCodigo.getText());
            cs.setString(2,campoNombre.getText());
            cs.setString(3,campoDescripcion.getText());
            cs.setString(4, campoCategoria.getSelectedItem().toString());
            cs.setString(5,date);
            cs.setString(6,campoCantidad.getText());
            cs.setString(7,campoCantidadMinima.getText());
            if(campoActivo.isSelected()){
            cs.setString(8,campoActivo.getText());
            }else if(campoInactivo.isSelected()){
            cs.setString(8,campoInactivo.getText());
            }
            cs.execute();
            
           
            JOptionPane.showMessageDialog(null,"Se inserto correctamente!");
        } catch(Exception e ){
            
            JOptionPane.showMessageDialog(null,"Error al isnertar registro!,error:"+e.toString());
        }
    }
        productos ObjetoProductos = new productos();
        ObjetoProductos.MostrarProductos(tabla);
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String dateeditar = sdf.format(campoVencimiento.getDate());
        conexion objetoConexion = new conexion();
        String editar ="UPDATE productos SET productos.codigo=?,productos.nombre=?,productos.descripcion=?,productos.categoria=?,productos.vencimiento=?,productos.cantidad=?,productos.cantidad_minima=?,productos.estado=? where productos.id=?";
        try{
        CallableStatement cs = objetoConexion.establecerConexion().prepareCall(editar);
            cs.setString(1,campoCodigo.getText());
            cs.setString(2,campoNombre.getText());
            cs.setString(3,campoDescripcion.getText());
            cs.setString(4, campoCategoria.getSelectedItem().toString());
            cs.setString(5,dateeditar);
            cs.setString(6, campoCantidad.getText());
            cs.setString(7, campoCantidadMinima.getText());
            if(campoActivo.isSelected()){
            cs.setString(8,campoActivo.getText());
            }else if(campoInactivo.isSelected()){
            cs.setString(8,campoInactivo.getText());
            }
            cs.setString(9,campoId.getText());
            cs.execute(); 
        JOptionPane.showMessageDialog(null,"Modificacion exitosa!");
        
        }catch (SQLException e){
            
             JOptionPane.showMessageDialog(null,"Error al intentar modificar, error:"+ e.toString()); 
        } 
        productos ObjetoProductos = new productos();
        ObjetoProductos.MostrarProductos(tabla);
    }//GEN-LAST:event_btnEditarActionPerformed

