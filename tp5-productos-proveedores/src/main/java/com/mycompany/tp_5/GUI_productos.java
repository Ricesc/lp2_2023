    private void tablaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaMouseClicked
        try{
             
            int fila = tabla.getSelectedRow();
            if (fila >=0){
                campoId.setText((tabla.getValueAt(fila,0).toString()));
                campoCodigo.setText((tabla.getValueAt(fila,1).toString()));
                campoNombre.setText((tabla.getValueAt(fila,2).toString()));
                campoDescripcion.setText((tabla.getValueAt(fila,3).toString()));
                campoCategoria.setSelectedItem(tabla.getValueAt(fila,4).toString());
                Date fecha = new SimpleDateFormat("yyyy-MM-dd").parse((String)tabla.getValueAt(fila,5).toString());
                campoVencimiento.setDate(fecha);
                campoCantidad.setText((tabla.getValueAt(fila,6).toString()));
                campoCantidadMinima.setText((tabla.getValueAt(fila,7).toString()));
               String estado= tabla.getValueAt(fila,8).toString();
               if(estado.equals("Activo")){
                   campoActivo.setSelected(true);
               } else {
                   campoInactivo.setSelected(true);
               }
               
            }   
            else{
                JOptionPane.showMessageDialog(null,"Fila no selecionada");
            }
            
        }catch(Exception e ){
             JOptionPane.showMessageDialog(null,"Error de selecion, error:"+e.toString());
           
        }
    }//GEN-LAST:event_tablaMouseClicked

